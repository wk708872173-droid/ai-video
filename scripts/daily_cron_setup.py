"""V3.2 REQ-305.b — Windows Task Scheduler 集成脚本生成器。

设计：
  - 生成 .ps1 + .bat 两套脚本（PS1 首选，bat 兜底老系统）
  - 同时生成对应的 uninstall 脚本
  - 纯字符串生成（不调真 schtasks / PowerShell），便于单测
  - 用户在 Windows 上以管理员权限运行生成的 setup_*.ps1 / setup_*.bat 即可注册每日任务

使用：
  1. 在仓库根目录跑（生成文件到 scripts/）：
     python -m scripts.daily_cron_setup
  2. 在 Windows 上右键 "以管理员身份运行" setup_daily_cron.ps1
  3. 验证：taskschd.msc 中可见任务名 "RMAP-DailyCron"
  4. 卸载：右键 "以管理员身份运行" uninstall_daily_cron.ps1
"""
from __future__ import annotations

import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any


# HH:MM 24h 严格校验（00:00 - 23:59）
_TRIGGER_TIME_RE = re.compile(r"^([01]\d|2[0-3]):[0-5]\d$")


# ---------- 默认配置 ----------

DEFAULT_TASK_NAME = "RMAP-DailyCron"
DEFAULT_TRIGGER_TIME = "09:00"
DEFAULT_PYTHON_EXE = "python"  # 默认 PATH 中的 python；用户可在生成时覆盖
DEFAULT_SCRIPT_ARGS = ["-m", "scripts.daily_cron", "--once"]  # 默认调 scripts/daily_cron.py


@dataclass
class SetupConfig:
    """生成 setup 脚本的配置。"""
    task_name: str = DEFAULT_TASK_NAME
    trigger_time: str = DEFAULT_TRIGGER_TIME  # "HH:MM" 24h
    python_exe: str = DEFAULT_PYTHON_EXE
    script_args: list[str] = field(default_factory=lambda: list(DEFAULT_SCRIPT_ARGS))
    workdir: str = ""  # 空 = 用脚本所在目录

    def to_dict(self) -> dict[str, Any]:
        return {
            "task_name": self.task_name,
            "trigger_time": self.trigger_time,
            "python_exe": self.python_exe,
            "script_args": list(self.script_args),
            "workdir": self.workdir,
        }


# ---------- PowerShell 脚本生成 ----------

def build_setup_ps1(cfg: SetupConfig) -> str:
    """生成 setup_daily_cron.ps1 内容（注册任务到 Windows Task Scheduler）。

    实现：
      - 用 schtasks /create 调用（无需 PowerShell ScheduledTasks module）
      - /sc daily /st 09:00 → 每日固定时间触发
      - /rl HIGHEST → 最高权限（绕过 UAC）
      - /tn "RMAP-DailyCron" → 任务名
    """
    if not cfg.task_name.strip():
        raise ValueError("task_name 不能为空")
    if not _TRIGGER_TIME_RE.match(cfg.trigger_time):
        raise ValueError(f"trigger_time 格式错误（应为 HH:MM 24h）：{cfg.trigger_time!r}")

    args_str = " ".join(_ps_quote(a) for a in cfg.script_args)
    py_quote = _ps_quote(cfg.python_exe)
    workdir_line = f'$workdir = "{_ps_escape(cfg.workdir)}"\n' if cfg.workdir else ""

    return f"""# Auto-generated by scripts.daily_cron_setup.py — DO NOT EDIT manually.
# 注册 Windows Task Scheduler 任务：每日 {cfg.trigger_time} 自动跑 daily_cron。
# 用法：右键本文件 → "以管理员身份运行 PowerShell"

$ErrorActionPreference = "Stop"
$taskName = "{_ps_escape(cfg.task_name)}"
$triggerTime = "{_ps_escape(cfg.trigger_time)}"
$pythonExe = {py_quote}
$scriptArgs = @({", ".join(_ps_quote(a) for a in cfg.script_args)})
{workdir_line}
$action_cmd = "`"$pythonExe`" " + ($scriptArgs -join " ")

Write-Host "[INFO] 注册 Windows Task Scheduler 任务：$taskName" -ForegroundColor Cyan
Write-Host "[INFO] 触发时间：每日 $triggerTime"
Write-Host "[INFO] 命令：$action_cmd"

# 若已存在同名任务，先删
$existing = schtasks /Query /TN "$taskName" 2>$null
if ($existing) {{
    Write-Host "[WARN] 已存在同名任务，先删除" -ForegroundColor Yellow
    schtasks /Delete /TN "$taskName" /F | Out-Null
}}

# 注册：每日触发 / 最高权限 / 失败也重启
$create_args = @(
    "/Create",
    "/SC", "DAILY",
    "/TN", "$taskName",
    "/TR", $action_cmd,
    "/ST", "$triggerTime",
    "/RL", "HIGHEST",
    "/F"
)
if ($workdir) {{
    $create_args += @("/WD", $workdir)
}}

$result = schtasks @create_args 2>&1
if ($LASTEXITCODE -eq 0) {{
    Write-Host "[OK] 任务注册成功：$taskName" -ForegroundColor Green
    Write-Host "[INFO] 验证：schtasks /Query /TN $taskName"
}} else {{
    Write-Host "[FAIL] schtasks 返回 $LASTEXITCODE：$result" -ForegroundColor Red
    exit 1
}}
"""


def build_uninstall_ps1(task_name: str = DEFAULT_TASK_NAME) -> str:
    """生成 uninstall_daily_cron.ps1 内容（删除任务）。"""
    if not task_name.strip():
        raise ValueError("task_name 不能为空")
    return f"""# Auto-generated by scripts/daily_cron_setup.py — DO NOT EDIT manually.
# 卸载 Windows Task Scheduler 任务：{task_name}

$ErrorActionPreference = "Stop"
$taskName = "{_ps_escape(task_name)}"

Write-Host "[INFO] 卸载任务：$taskName" -ForegroundColor Cyan
$existing = schtasks /Query /TN "$taskName" 2>$null
if (-not $existing) {{
    Write-Host "[INFO] 任务不存在，无需卸载" -ForegroundColor Yellow
    exit 0
}}
schtasks /Delete /TN "$taskName" /F
if ($LASTEXITCODE -eq 0) {{
    Write-Host "[OK] 任务已卸载：$taskName" -ForegroundColor Green
}} else {{
    Write-Host "[FAIL] 卸载失败：schtasks exit=$LASTEXITCODE" -ForegroundColor Red
    exit 1
}}
"""


# ---------- cmd / bat 脚本生成 ----------

def build_setup_bat(cfg: SetupConfig) -> str:
    """生成 setup_daily_cron.bat 内容（cmd fallback，老 Windows / 非 PS 环境）。"""
    if not cfg.task_name.strip():
        raise ValueError("task_name 不能为空")
    if not _TRIGGER_TIME_RE.match(cfg.trigger_time):
        raise ValueError(f"trigger_time 格式错误（应为 HH:MM 24h）：{cfg.trigger_time!r}")

    args_str = " ".join(_bat_quote(a) for a in cfg.script_args)
    py_quote = _bat_quote(cfg.python_exe)
    workdir_line = f'set "WORKDIR={cfg.workdir}"\n' if cfg.workdir else ""

    return f"""@echo off
REM Auto-generated by scripts.daily_cron_setup.py — DO NOT EDIT manually.
REM 注册 Windows Task Scheduler 任务：每日 {cfg.trigger_time} 自动跑 daily_cron。
REM 用法：右键本文件 → "以管理员身份运行"

setlocal EnableDelayedExpansion
{workdir_line}
set "TASK_NAME={_bat_escape(cfg.task_name)}"
set "TRIGGER_TIME={_bat_escape(cfg.trigger_time)}"
set "PYTHON_EXE={py_quote}"
set "SCRIPT_ARGS={_bat_escape(args_str)}"

echo [INFO] 注册 Windows Task Scheduler 任务：%TASK_NAME%
echo [INFO] 触发时间：每日 %TRIGGER_TIME%

REM 若已存在同名任务，先删
schtasks /Query /TN "%TASK_NAME%" >nul 2>&1
if %ERRORLEVEL% equ 0 (
    echo [WARN] 已存在同名任务，先删除
    schtasks /Delete /TN "%TASK_NAME%" /F >nul 2>&1
)

REM 注册任务
set "ACTION_CMD=\"%PYTHON_EXE%\" %SCRIPT_ARGS%"
schtasks /Create /SC DAILY /TN "%TASK_NAME%" /TR "%ACTION_CMD%" /ST %TRIGGER_TIME% /RL HIGHEST /F
if %ERRORLEVEL% equ 0 (
    echo [OK] 任务注册成功：%TASK_NAME%
    echo [INFO] 验证：schtasks /Query /TN %TASK_NAME%
) else (
    echo [FAIL] schtasks 返回 %ERRORLEVEL%
    exit /b 1
)
endlocal
"""


def build_uninstall_bat(task_name: str = DEFAULT_TASK_NAME) -> str:
    """生成 uninstall_daily_cron.bat 内容（cmd fallback 卸载）。"""
    if not task_name.strip():
        raise ValueError("task_name 不能为空")
    return f"""@echo off
REM Auto-generated by scripts.daily_cron_setup.py — DO NOT EDIT manually.
REM 卸载 Windows Task Scheduler 任务：{task_name}

setlocal
set "TASK_NAME={_bat_escape(task_name)}"

echo [INFO] 卸载任务：%TASK_NAME%
schtasks /Query /TN "%TASK_NAME%" >nul 2>&1
if %ERRORLEVEL% neq 0 (
    echo [INFO] 任务不存在，无需卸载
    exit /b 0
)
schtasks /Delete /TN "%TASK_NAME%" /F
if %ERRORLEVEL% equ 0 (
    echo [OK] 任务已卸载：%TASK_NAME%
) else (
    echo [FAIL] 卸载失败：schtasks exit=%ERRORLEVEL%
    exit /b 1
)
endlocal
"""


# ---------- 落盘辅助 ----------

def write_setup_files(target_dir: str | Path, cfg: SetupConfig | None = None) -> dict[str, Path]:
    """生成 4 个文件到 target_dir，返回 {filename: path} 映射。

    Files:
      - setup_daily_cron.ps1
      - setup_daily_cron.bat
      - uninstall_daily_cron.ps1
      - uninstall_daily_cron.bat
    """
    cfg = cfg or SetupConfig()
    out_dir = Path(target_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    files = {
        "setup_daily_cron.ps1": build_setup_ps1(cfg),
        "setup_daily_cron.bat": build_setup_bat(cfg),
        "uninstall_daily_cron.ps1": build_uninstall_ps1(cfg.task_name),
        "uninstall_daily_cron.bat": build_uninstall_bat(cfg.task_name),
    }
    written: dict[str, Path] = {}
    for name, content in files.items():
        p = out_dir / name
        p.write_text(content, encoding="utf-8")
        written[name] = p
    return written


# ---------- 字符串转义工具 ----------

def _ps_quote(s: str) -> str:
    """PowerShell 字符串引号：双引号包裹 + 内部双引号转义。"""
    return '"' + s.replace('"', '`"').replace("'", "`'") + '"'


def _ps_escape(s: str) -> str:
    """PowerShell 字符串内字符转义（不含引号包装）。"""
    return s.replace('"', '`"').replace("`", "``")


def _bat_quote(s: str) -> str:
    """cmd 字符串引号：双引号包裹 + 内部双引号转义（罕见）。"""
    return '"' + s.replace('"', '""') + '"'


def _bat_escape(s: str) -> str:
    """cmd 字符串内字符转义。"""
    # 百分号 % 在 set 中要写成 %%
    return s.replace("%", "%%")


# ---------- CLI ----------

def main(argv: list[str] | None = None) -> int:
    import argparse
    p = argparse.ArgumentParser(
        prog="daily_cron_setup",
        description="V3.2 REQ-305.b 生成 Windows Task Scheduler 集成脚本",
    )
    p.add_argument("--target-dir", default="scripts",
                   help="生成文件输出目录（默认 scripts/）")
    p.add_argument("--task-name", default=DEFAULT_TASK_NAME,
                   help=f"任务名（默认 {DEFAULT_TASK_NAME}）")
    p.add_argument("--trigger-time", default=DEFAULT_TRIGGER_TIME,
                   help=f"每日触发时间 HH:MM（默认 {DEFAULT_TRIGGER_TIME}）")
    p.add_argument("--python-exe", default=DEFAULT_PYTHON_EXE,
                   help=f"Python 可执行路径（默认 {DEFAULT_PYTHON_EXE}）")
    p.add_argument("--workdir", default="",
                   help="任务工作目录（默认空）")
    args = p.parse_args(argv)

    cfg = SetupConfig(
        task_name=args.task_name,
        trigger_time=args.trigger_time,
        python_exe=args.python_exe,
        script_args=list(DEFAULT_SCRIPT_ARGS),
        workdir=args.workdir,
    )
    written = write_setup_files(args.target_dir, cfg)
    print(f"[OK] 已生成 {len(written)} 个文件到 {args.target_dir}/:")
    for name, path in written.items():
        print(f"  - {path}")
    print()
    print("下一步：在 Windows 上右键 setup_daily_cron.ps1 → 以管理员身份运行")
    print("卸载：右键 uninstall_daily_cron.ps1 → 以管理员身份运行")
    return 0


if __name__ == "__main__":
    sys.exit(main())
